import express from 'express';
import { getUserProfile, updateUserProfile, getUsers } from '../controllers/userController.js';
import { retiredAuthentication } from '../controllers/authController.js';
import { protect, admin } from '../middleware/authMiddleware.js';
const router = express.Router();
router.post('/register', retiredAuthentication);
router.post('/login', retiredAuthentication);
router.route('/profile').get(protect, getUserProfile).put(protect, updateUserProfile);
router.get('/', protect, admin, getUsers);
export default router;
